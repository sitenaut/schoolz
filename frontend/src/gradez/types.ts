// GET /students/{id}/bucket3/grades - the Genesis gradebook as captured.
export type CourseGrade = {
  course_code: string;
  course_section: string;
  course_name: string | null;
  marking_period: string;
  grade_percent: number | null;
  last_grade_posted: string | null;
};

export type GradeEntry = {
  external_uid: string;
  course_code: string;
  course_section: string;
  course_name: string | null;
  marking_period: string | null;
  // As Genesis prints it: "Mon 11/9", no year.
  weekday_date: string;
  title: string;
  description: string | null;
  category: string | null;
  score_earned: number | null;
  score_possible: number | null;
  percent: number | null;
  status: string | null;
  is_updated: boolean;
  // When schoolz first read this entry with a grade on it; null while ungraded.
  graded_at: string | null;
};

export type Grades = {
  course_grades: CourseGrade[];
  entries: GradeEntry[];
  marking_periods: MarkingPeriod[];
  marking_period_discrepancies: string[];
};

// GET /students/{id}/bucket3/audit - what Classroom and Genesis each list.
export type AuditWorkItem = {
  external_uid: string;
  course_name: string | null;
  title: string;
  due_raw: string | null;
};

